const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
async function run() {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    for (const [width,height] of [[1920,940],[2560,1300],[1440,810],[393,852]]) {
      const page = await browser.newPage({viewport:{width,height}});
      const errors = [];
      page.on('pageerror', e => errors.push(e.message));
      await page.goto(process.argv[2], {waitUntil:'domcontentloaded'});
      await page.click('#demo');
      const trigger = page.locator('#pick-month');
      const initialMonth = await trigger.innerText();
      const currentYear = Number(initialMonth.split('년')[0]);
      await trigger.click();
      const picker = page.locator('#month-menu');
      assert.equal(await picker.locator('[data-month]').count(),12);
      const pickerBox = await picker.boundingBox();
      assert.ok(pickerBox.x >= 0 && pickerBox.x+pickerBox.width <= width);
      await picker.getByRole('button',{name:'이전 연도'}).click();
      await picker.getByRole('button',{name:'12월',exact:true}).click();
      assert.equal(await trigger.innerText(),(currentYear-1)+'년 12월');
      assert.equal(await page.locator('.day.selected').getAttribute('data-date'),(currentYear-1)+'-12-01');
      await trigger.click();
      await picker.getByRole('button',{name:'다음 연도'}).click();
      await picker.getByRole('button',{name:initialMonth.split('년 ')[1],exact:true}).click();
      await trigger.click();
      await page.keyboard.press('Escape');
      assert.equal(await picker.isVisible(),false);
      await page.evaluate(()=>document.fonts.ready);
      assert.ok(await page.evaluate(()=>[...document.fonts].some(face=>face.family.includes('Jalnan') && face.status==='loaded')
        && ['.brand h1','#pick-month'].every(s=>getComputedStyle(document.querySelector(s)).fontFamily.startsWith('"Jalnan 2"'))));
      assert.equal(await page.locator('.monthly .budget-top strong').innerText(),'0원');
      assert.ok(await page.evaluate(()=>{
        const size = id=>parseFloat(getComputedStyle(document.getElementById(id)).fontSize);
        return size('zero') === size('detail-add') && size('zero') >= 16;
      }));
      await page.click('#zero');
      assert.equal(await page.locator('.day.selected .stamp').count(),1);
      await page.evaluate(()=>document.fonts.ready);
      if(width>=1440){
        const dimensions=await page.evaluate(()=>({
          height:document.documentElement.scrollHeight,width:document.documentElement.scrollWidth,
          viewport:innerHeight,broken:[...document.images].filter(i=>i.complete&&!i.naturalWidth).length
        }));
        assert.ok(dimensions.height<=height && dimensions.width<=width,JSON.stringify(dimensions));
        assert.equal(dimensions.broken,0);
      }
      await page.click('.day.selected');
      await page.fill('#dialog [name=use]','테스트 점심');
      await page.fill('#dialog [name=amount]','999999999999');
      await page.click('#modal-save');
      assert.equal(await page.locator('.day.selected .stamp').count(),0);
      assert.equal(await page.locator('.day.selected .day-amount').textContent(),'999,999,999,999');
      const fits = await page.locator('.day.selected').evaluate(cell=>{
        const range=document.createRange();range.selectNodeContents(cell.querySelector('.day-amount'));
        const bounds=cell.getBoundingClientRect();
        return document.documentElement.scrollWidth<=innerWidth && [...range.getClientRects()].every(r=>r.left>=bounds.left-1 && r.right<=bounds.right+1 && r.bottom<=bounds.bottom+1);
      });
      assert.ok(fits,'calendar amount overflow at '+width);
      await page.click('[data-edit]');
      assert.equal(await page.locator('[name=note]').inputValue(),'테스트 점심');
      await page.fill('[name=note]','수정한 사용처');
      await page.fill('#modal-form [name=amount]','162000');
      await page.click('#modal-save');
      assert.equal(await page.locator('.entry-note').textContent(),'수정한 사용처');
      const w = await page.locator('.week-range').innerText();
      await page.click('#open-plan');
      await page.fill('[name=memo]','이번 달 여행 준비');
      await page.getByText('달·주 예산',{exact:true}).click();
      await page.fill('input[name="'+w.slice(0,10)+'"]','150000');
      await page.click('#modal-save');
      assert.match(await page.locator('.weekly .balance').innerText(),/−12,000/);
      await page.click('[data-delete]');
      await page.click('#undo');
      await page.click('[data-delete]');
      await page.click('#trash');
      await page.click('[data-restore]');
      await page.click('[data-history]');
      await page.locator('[data-revision]').last().click();
      assert.equal(await page.locator('.day.selected .day-amount').textContent(),'999,999,999,999');
      const downloaded=page.waitForEvent('download');
      await page.click('#export');
      const payload=await fs.readFile(await (await downloaded).path());
      await page.click('[data-delete]');
      await page.locator('#file').setInputFiles({name:'restore.json',mimeType:'application/json',buffer:payload});
      await page.click('#import-confirm');
      assert.equal(await page.locator('.entry-note').textContent(),'테스트 점심');
      const originalDay = await page.locator('.day.selected').getAttribute('data-date');
      await page.click('#page-report');
      assert.equal(await page.locator('#report-total').textContent(),'999,999,999,999원');
      assert.equal(await page.locator('.calendar').count(),0);
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
      await page.click('#prev');
      assert.equal(await page.locator('#report-total').textContent(),'0원');
      await page.click('#prev');
      assert.equal(await page.locator('.report-page').count(),1);
      await page.click('#page-calendar');
      assert.equal(await page.locator('.day-amount').count(),0);
      await page.click('#next');
      await page.click('#next');
      await page.click('#page-report');
      await page.click('[data-report-date="' + originalDay + '"]');
      assert.equal(await page.locator('.day.selected').getAttribute('data-date'),originalDay);
      assert.equal(await page.locator('.entry').count(),1);
      await page.locator('#file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{}')});
      await page.locator('#status').filter({hasText:'가져오기 실패'}).waitFor();
      assert.equal(await page.locator('.entry').count(),1);
      await page.click('.day.selected');
      await page.fill('[name=dayNote]','날짜별 메모');
      await page.click('#modal-save');
      assert.match(await page.locator('.saved-day-note').innerText(),/날짜별 메모/);
      const recordedCell = page.locator('[data-date="' + originalDay + '"]');
      assert.equal(await recordedCell.locator('.calendar-note').innerText(),'날짜별 메모');
      await page.click('#prev');
      await page.click('#next');
      assert.equal(await recordedCell.locator('.calendar-note').innerText(),'날짜별 메모');
      const bounds = await recordedCell.evaluate(cell => {
        const note = cell.querySelector('.calendar-note').getBoundingClientRect();
        const amount = cell.querySelector('.day-amount').getBoundingClientRect();
        return note.height > 8 && note.bottom <= amount.top + 1 && amount.bottom <= cell.getBoundingClientRect().bottom + 1;
      });
      assert.ok(bounds,'Memo and amount must remain visible inside their day at '+width);
      assert.equal(await page.locator('.entry').count(),1);
      assert.equal(await page.locator('.saved-plan').innerText(),'이번 달 여행 준비');
      await page.click('#page-fixed');
      await page.click('#open-plan');
      await page.click('[data-add-row=fixed]');
      await page.fill('[name=fixedName]','통신비');
      await page.fill('[name=fixedValue]','21000');
      await page.click('#modal-save');
      assert.match(await page.locator('.fixed-list').innerText(),/21,000/);
      await page.click('#category-manage');
      await page.click('#new-category');
      assert.equal(await page.locator('.category-row').count(),12);
      await page.locator('[name=categoryName]').last().fill('반려생활');
      await page.locator('.category-row[data-id=online] [name=merchant]').fill('쿠팡');
      await page.click('#modal-save');
      await page.click('#page-calendar');
      await page.click('.day.selected');
      await page.locator('#dialog').getByRole('button',{name:'온라인쇼핑'}).click();
      assert.equal(await page.locator('#dialog [name=use]').inputValue(),'쿠팡');
      await page.fill('#dialog [name=purchase]','세탁세제');
      await page.fill('#dialog [name=amount]','12500');
      await page.click('#modal-save');
      await page.click('#page-report');
      const group=page.locator('.category-breakdown').filter({hasText:'온라인쇼핑'});
      await group.locator('summary').click();
      assert.match(await group.innerText(),/쿠팡 · 세탁세제/);
      assert.match(await group.innerText(),/12,500원/);
      await page.click('#category-manage');
      await page.locator('.category-row[data-id=online] [name=categoryName]').fill('인터넷 구매');
      await page.click('#modal-save');
      const renamed=page.locator('.category-breakdown').filter({hasText:'인터넷 구매'});
      await renamed.locator('summary').click();
      assert.match(await renamed.innerText(),/쿠팡 · 세탁세제/);
      assert.deepEqual(errors,[]);
      await page.close();
      console.log(width+'px: CRUD, undo/trash/history, export/import, invalid restore, stamp, negative budget, amount bounds PASS');
    }
  } finally { await browser.close(); }
}
run().catch(e=>{console.error(e);process.exitCode=1});
